    PRIMARY KEY (ID),
    UNIQUE KEY UQ_TARJETAS_TOKEN (TOKEN),
    CONSTRAINT FK_TARJETAS_INFO FOREIGN KEY (ID) REFERENCES INFORMACION_PAGOS (ID) ON DELETE CASCADE
